class CompileError(Exception):
    pass


def real_date(v, until_tomorrow=False):
    """A calendar date written YYYY-MM-DD (not 0000-99-99). With until_tomorrow, one from 2020 to tomorrow at the latest
    (Paris is ahead of the workspace's UTC for an hour or two a night): a permission is never dated in the future."""
    if not isinstance(v, str) or not WORDS_DATE.fullmatch(v):
        return False
    try:
        d = datetime.date.fromisoformat(v)
    except ValueError:
        return False
    if until_tomorrow and not (FIRST_DATE <= d <= datetime.date.today() + datetime.timedelta(days=1)):
        return False
    return True


def bare_words(said):
    """Joe's words as judged: format and control characters out, ends trimmed."""
    return ''.join(ch for ch in said if unicodedata.category(ch) not in ('Cf', 'Cc')).strip() if isinstance(said, str) else ''


def not_joes_words(bare):
    """Why these words are not Joe's own (a note, a test's words), or None."""
    if bare[:1] in NOTE_OPENERS:
        return 'a note'
    if NOT_WORDS.search(re.sub(r'[^a-z0-9]', '', bare.lower())):
        return 'a test\'s words'
    return None


def load_fields(obj):
    """The account's person fields as {name: {type, format, firstClassField, createdBy, readOnly}}. Accepts this package's map
    ({"fields": {name: {...}}}), a list of fields, the person object, or the whole GET /v1/schemas response."""
    if isinstance(obj, dict) and isinstance(obj.get('fields'), dict):
        return obj['fields']
    if isinstance(obj, dict) and isinstance(obj.get('objects'), list):
        person = [o for o in obj['objects'] if isinstance(o, dict) and o.get('name') == 'person']
        if len(person) != 1:
            raise CompileError('--fields: the schemas response has no single object named person')
        obj = person[0]
    if isinstance(obj, dict) and isinstance(obj.get('fields'), list):
        obj = obj['fields']
    if isinstance(obj, list) and obj and all(isinstance(f, dict) and isinstance(f.get('name'), str) for f in obj):
        return {f['name']: {k: f[k] for k in ('type', 'format', 'firstClassField', 'createdBy', 'readOnly') if k in f} for f in obj}
    raise CompileError('--fields: not a shape the compiler knows ({"fields": {...}}, a list of fields, '
                       'the person object, or the GET /v1/schemas response)')


def load_tags(obj):
    """The account's tag names. Accepts the GET /v1/tags-management response as saved ({"tags": [{"tag": …}]}), the
    counts response ({"tagCounts": [{"tag": …}]}), a list of {"tag": …}, or a list of names."""
    if isinstance(obj, dict):
        obj = obj.get('tags', obj.get('tagCounts'))
    if isinstance(obj, list) and all(isinstance(t, str) or (isinstance(t, dict) and isinstance(t.get('tag'), str)) for t in obj):
        return {t if isinstance(t, str) else t['tag'] for t in obj}
    raise CompileError('--tags: not a shape the compiler knows (the GET /v1/tags-management response, or a list of names)')


TBD = re.compile(r'^TBD(:|$)')


def find_tbd(obj, path='$'):
    """Paths of every value still to be decided ("TBD", "TBD:…") in a spec or manifest. Prose is not a value:
    anything under a "note" or "notes" key (a manifest's note, a spec's note, the sticky notes on a canvas) is skipped."""
    out = []
    if isinstance(obj, str):
        if TBD.match(obj):
            out.append(path)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if k in ('note', 'notes'):
                continue
            out.extend(find_tbd(v, '%s.%s' % (path, k)))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            out.extend(find_tbd(v, '%s[%d]' % (path, i)))
    return out


def live_ledger(ledger):
    """The ledger without the entries it marks "state": "deleted" or "failed" (v1.01): Joe deleted those objects by
    hand, or they are failed drafts waiting for him to, so their keys and IDs are never used again."""
    out = {}
    for kind, entries in (ledger or {}).items():
        if isinstance(entries, dict):
            entries = {k: v for k, v in entries.items() if not (isinstance(v, dict) and v.get('state') in DEAD_STATES)}
        out[kind] = entries
    return out


def dead_ids(ledger):
    """{kind: {id: state}} for the ledger's deleted and failed flows, segments and emails, so a spec that names one
    by its Encharge ID, not its key, is refused too."""
    out = {'flows': {}, 'segments': {}, 'emails': {}}
    for kind in out:
        entries = (ledger or {}).get(kind)
        if isinstance(entries, dict):
            for v in entries.values():
                if isinstance(v, dict) and v.get('state') in DEAD_STATES and isinstance(v.get('id'), int):
                    out[kind][v['id']] = v['state']
    return out


def dead_keys(ledger):
    """{kind: {key or name: state}} for the ledger's deleted and failed entries of every kind: a spec that names one
    is refused, not merely warned about (the second review of v1.01), unless this build makes it anew."""
    out = {'flows': {}, 'segments': {}, 'emails': {}, 'tags': {}, 'fields': {}}
    for kind in out:
        entries = (ledger or {}).get(kind)
        if isinstance(entries, dict):
            for k, v in entries.items():
                if isinstance(v, dict) and v.get('state') in DEAD_STATES:
                    out[kind][k] = v['state']
    return out


class Context:
    def __init__(self, catalogue, ledger=None, permissions=None, fields=None, tag_groups=None, tags=None, offline_permissions=False):
        self.cat = catalogue
        self.offline_permissions = offline_permissions   # --offline-permissions: the suites' own words are taken (v1.02)
        self.switch_over = False         # --switch-over: only the switch-over's segment edits (v1.02, D1)
        self.switch_over_flows = []      # with it: the manifest's flows that enter that segment [(key, name)]
        self.router_absent = set()       # manifest fields the FlowMattic routers own that the account lacks: never made here
        self.left_for_switch_over = []   # the edits an ordinary objects plan leaves out, for the switch-over
        self.ledger = live_ledger(ledger)
        self.raw_ledger = ledger if isinstance(ledger, dict) else {}   # with its failed and deleted entries
        self.dead = dead_ids(ledger)
        self.dead_keys = dead_keys(ledger)
        self.permissions = permissions or []
        self.fields = load_fields(fields) if fields is not None else None
        # a tag or field the ledger holds live is in the account, whatever the session's first read says (reconcile checks
        # that before the first run): so a build never makes again one a failed run made and Joe kept (the third review of
        # the fixes: the rebuild stopped at the guard, "already exists")
        led_fields = (self.ledger.get('fields') or {}) if isinstance(self.ledger.get('fields'), dict) else {}
        if self.fields is not None:
            for n, v in led_fields.items():
                if n not in self.fields and isinstance(v, dict):   # live (live_ledger left out failed and deleted), any state
                    self.fields[n] = dict({'type': 'string', 'firstClassField': False, 'readOnly': False, 'createdBy': 'user'},
                                          **({'format': 'date-time'} if v.get('type') == 'date' else {}))
        self.tag_groups = tag_groups or {}
        self.account_tags = load_tags(tags) if tags is not None else None   # None: no --tags, so tags are not checked
        led_tags = (self.ledger.get('tags') or {}) if isinstance(self.ledger.get('tags'), dict) else {}
        if self.account_tags is not None:
            self.account_tags |= {n for n, v in led_tags.items() if isinstance(v, dict)}   # live, any state
        self.new_tags = set()     # tags this build creates (the objects plan, or --manifest for a flow)
        self.later_tags = set()   # tags only in the manifest's later block (parked)
        self.later_fields = set() # fields only in the manifest's later block (parked)
        self.uncaptured = []      # steps whose creation flags were never captured, for one line per run
        self.first_class = set(catalogue.get('firstClassFields', {}).get('names', []))
        self.errors, self.warnings, self.used_permissions = [], [], []
        self.new_fields = {}   # fields this build creates: {name: 'text'|'date'}
        self.where = ('a condition', 'check')   # (the place, its kind) of the rows being compiled, for messages
        self.numeric_segments = set()   # new segments holding a number written as text on a Text field (gap A12)
        self.new_segments = set()     # segments this plan creates, in the order compiled so far
        self.later_segments = set()   # segments this plan creates after the one being compiled (and that one)
        self.parked_segments = set()  # segments only in the manifest's later block (parked)
        self.build_segments = set()   # for a flow: the segments the objects plan creates (--manifest shared.segments)
        self.allow_parked = False     # --allow-parked: compile a parked flow for a dry run; the plan is marked dryRunOnly
        self.dry_run_only = []        # why this plan may not run (a parked flow compiled for a dry run)
        self.manifest_status = {}     # --manifest's flows: {key: status}, checked against each spec's own
        self.build_emails = set()     # for a flow: the emails the objects plan creates (--manifest shared.emails)
        for p in find_tbd(self.tag_groups, 'tag-groups'):
            self.err('%s is still to be decided (TBD); a tag group may not hold one' % p)
        self.check_ledger_ids(ledger)
        self.check_permissions()

    def err(self, msg):
        self.errors.append(msg)

    def check_ledger_ids(self, ledger):
        """One Encharge object, one ledger entry (the fifth review of v1.01): an ID under two keys of a kind, such as an old
        entry copied to <key>-old-<date> while the key still holds it, would leave the runner refusing the key's ref for
        ever, or name one object twice. Since v1.02 every flow, segment and email entry carries its ID as a whole number
        (the review of the fixes: an alias holding "1059368" as text slipped past the switch-over's gate and this check)."""
        for kind in ('flows', 'segments', 'emails'):
            entries = (ledger or {}).get(kind)
            if not isinstance(entries, dict):
                continue
            by_id = {}
            for k, v in entries.items():
                if not isinstance(v, dict) or not isinstance(v.get('id'), int) or isinstance(v.get('id'), bool):
                    self.err('the ledger\'s %s.%s has no whole-number id: settle the ledger first (pagecmd.py ledger check)' % (kind, k))
                    continue
                if isinstance(v, dict) and isinstance(v.get('id'), int) and not isinstance(v.get('id'), bool):
                    by_id.setdefault(v['id'], []).append('%s (%s)' % (k, v.get('state') or 'live'))
            for i, keys in sorted(by_id.items()):
                if len(keys) > 1:
                    self.err('the ledger holds Encharge %s %d under %s: one object, one entry; settle the ledger first'
                             % (kind[:-1], i, ' and '.join(keys)))

    def check_permissions(self):
        """A permission for a segment or a flow names it by key and by Encharge ID; both must agree with the ledger,
        so an entry cannot open one object while naming another. Since v1.02 (review of v1.01, N4) every entry carries
        Joe's own words (joeSaid) and the day he gave them (date, YYYY-MM-DD): an entry without them, or whose words are
        a note in brackets, such as the offline suites' "(offline test only)", is refused unless --offline-permissions."""
        if not isinstance(self.permissions, list):
            self.err('permissions: a list of entries, one per object and action')
            self.permissions = []
            return
        for p in self.permissions:
            if not isinstance(p, dict):
                self.err('permission %s: an entry is {"object", "action", "joeSaid", "date"}' % json.dumps(p)[:80])
                continue
            obj = str(p.get('object', ''))
            kind, _, key = obj.partition(':')
            if not self.offline_permissions:
                said = p.get('joeSaid')
                bare = bare_words(said)
                if not bare:
                    self.err('permission %s: no joeSaid; a permission is Joe\'s own words in the chat, naming the object (rule 4)' % obj)
                elif not_joes_words(bare):
                    self.err('permission %s: joeSaid is %s, %s, not Joe\'s words (rule 4); the offline suites\' permissions '
                             'are never used for a real build' % (obj, json.dumps(said)[:80], not_joes_words(bare)))
                if not real_date(p.get('date'), until_tomorrow=True):
                    self.err('permission %s: date %s is not the day Joe gave it, as YYYY-MM-DD, and not after today (rule 4)' % (obj, json.dumps(p.get('date'))))
            if '*' in obj:
                self.err('permission %s: a permission names one object; there is no wildcard' % obj)
            if p.get('action') not in PERMISSION_ACTIONS:
                self.err('permission %s: action %s is not one of %s (a permission names one action)'
                         % (obj, json.dumps(p.get('action')), ', '.join(sorted(PERMISSION_ACTIONS))))
            if kind not in ('segment', 'flow'):
                continue
            if p.get('id') is None:
                self.err('permission %s needs the Encharge id as well (the guard matches the id)' % obj)
                continue
            if isinstance(p.get('id'), int) and p['id'] in self.dead.get(kind + 's', {}):
                self.err('permission %s names Encharge %s %d, which the ledger marks %s' % (obj, kind, p['id'], self.dead[kind + 's'][p['id']]))
                continue
            if key.isdigit():
                if key != str(p['id']):
                    self.err('permission %s carries id %s' % (obj, p['id']))
                continue
            if key in self.dead_keys.get(kind + 's', {}):
                self.err('permission %s names %s "%s", which the ledger marks %s' % (obj, kind, key, self.dead_keys[kind + 's'][key]))
                continue
            led = (self.ledger.get(kind + 's') or {}).get(key)
            if led is None:
                self.err('permission %s names id %s, but "%s" is not in the ledger' % (obj, p['id'], key))
            elif str(led.get('id')) != str(p['id']):
                self.err('permission %s names id %s, but the ledger has %s for it' % (obj, p['id'], led.get('id')))

    def has_permission(self, obj, action):
        """The entry that permits this, or None. Only a segment or a flow is matched by its Encharge id as well, as
        the guard does; anything else must be named exactly."""
        kind, _, name = obj.partition(':')
        for p in self.permissions:
            same = p.get('object') == obj or (kind in ('segment', 'flow') and p.get('id') is not None
                                               and str(p.get('id')) == name and str(p.get('object', '')).startswith(kind + ':'))
            if same and p.get('action') == action:
                return p
        return None

    def permitted(self, obj, action):
        p = self.has_permission(obj, action)
        if p is not None and not any(u is p for u in self.used_permissions):
            # v1.09 (P13): each entry once, however many steps use it, so the report's count is the page's (lesson B9)
            self.used_permissions.append(p)
        return p is not None

    def known(self, kind, key):
        return key in (self.ledger.get(kind) or {})

    def check_dead(self, kind, ref, where):
        """An object the ledger marks deleted or failed is never named again (v1.01), by Encharge ID or by key (by name
        for a tag or a field). Callers leave out what this build itself makes anew (a rebuild under the same key)."""
        if isinstance(ref, bool):
            return
        if isinstance(ref, int) and ref in self.dead.get(kind, {}):
            self.err('%s names Encharge %s %d, which the ledger marks %s: it is never used again' % (
                where, kind[:-1], ref, self.dead[kind][ref]))
        elif isinstance(ref, str) and ref in self.dead_keys.get(kind, {}):
            self.err('%s names %s "%s", which the ledger marks %s: it is never used again (a rebuild takes the key once '
                     'the ledger moves the old entry to a key of its own)' % (where, kind[:-1], ref, self.dead_keys[kind][ref]))

    def dead_reuse(self, kind, name):
        """Why a manifest tag or field ('tags' or 'fields') that the ledger marks deleted or failed cannot be made anew by
        this build, or None (the third review of v1.01). A tag or a field is one per name in Encharge, so the build would
        reuse it, not make it, while the ledger kept it on Joe's delete list: one marked failed still exists (a draft he
        is to delete), and one marked deleted that the account still holds means the ledger is wrong."""
        state = self.dead_keys.get(kind, {}).get(name)
        if state is None:
            return None
        what = kind[:-1]
        if state == 'failed':
            return ('%s "%s": the ledger marks it failed (still in Encharge, on Joe\'s delete list), so this build would reuse '
                    'it, not make it anew. Settle it with Joe first: once he has deleted it (the ledger then says deleted), a '
                    'build makes it anew; if he keeps it, pagecmd.py ledger keep records that, and this build uses it as the account\'s' % (what, name))
        have = self.account_tags if kind == 'tags' else self.fields
        if have is not None and name in have:
            return ('%s "%s": the ledger marks it deleted, but the account still holds it: the ledger is wrong, or the '
                    'deletion did not happen; settle it with Joe first' % (what, name))
        return None

    def check_tag(self, tag, where):
        """With --tags, a tag a flow or segment uses must exist: in the account, in the ledger, or created by this
        build. A product or refund tag not live yet is a warning (FlowMattic creates it at product go-live); a tag
        only in the manifest's later block, or in none of these, is refused (a misspelling, or a tag nothing creates)."""
        if isinstance(tag, str) and tag not in self.new_tags:
            self.check_dead('tags', tag, where)
        if self.account_tags is None or not isinstance(tag, str):
            return
        if tag in self.account_tags or tag in self.new_tags or self.known('tags', tag):
            return
        if tag in self.later_tags:
            self.err('%s: tag "%s" is only in the manifest\'s later block (parked); un-park it first' % (where, tag))
        elif PROTECTED_TAG.search(tag):
            warn = ('%s: tag "%s" is not in the account yet. FlowMattic creates product and refund tags when the product '
                    'goes live; until then nothing adds it' % (where, tag))
            if warn not in self.warnings:
                self.warnings.append(warn)
        else:
            self.err('%s: tag "%s" is not in the account, the ledger or this build (--manifest): a misspelling, or a tag '
                     'nothing creates' % (where, tag))


def is_router_field(name):
    return isinstance(name, str) and name.lower() in {f.lower() for f in ROUTER_FIELDS}


def router_field_why(name):
    return ('field "%s" is one the FlowMattic routers write: the builder never creates it (the guard refuses to), and the '
            'account\'s fields do not hold it. It must be in Encharge first, made by hand as a user field (Text), then read '
            'again into fields.json; or the email set takes it out of the manifest\'s shared fields' % name)


